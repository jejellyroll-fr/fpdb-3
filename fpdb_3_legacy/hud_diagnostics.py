"""Launch identity that a HUD bug report can be argued from.

A report of "two overlays per player" cannot be settled from the application
log as it stands: several launches share one file, the HUD child and the GUI
parent look alike, and nothing says which executable actually ran. Every
question that matters -- which build, which process, how many of them, run from
where -- is answered by the few facts collected here and written once per
process as a banner.

The session id is generated by whichever process starts first and passed to
children through the environment, so the parent GUI and its HUD child share
one id while a relaunch gets a new one. That is what makes "separate the logs
by session" a grep rather than a guess.
"""

from __future__ import annotations

import contextlib
import faulthandler
import os
import sys
import threading
import traceback
import uuid
from datetime import datetime
from pathlib import Path
from types import TracebackType
from typing import Any, Protocol

# macOS runs a quarantined app from a read-only, randomly named mount instead
# of where the user put it. The mount path is the only visible sign of it, and
# it also explains TCC grants that silently stop applying after an update.
APP_TRANSLOCATION_MARKER = "/AppTranslocation/"

#: Children inherit the launch id through this variable.
SESSION_ENV_VAR = "FPDB_SESSION_ID"

#: Values accepted for the ``role`` field of an identity banner.
ROLE_MAIN = "main"
ROLE_HUD = "hud"

#: Where each process keeps its native crashes and uncaught exceptions.
HUD_CRASH_LOG_NAME = "HUD-crash.txt"
MAIN_CRASH_LOG_NAME = "fpdb-crash.txt"


def session_id() -> str:
    """Return the id shared by every log line of this launch.

    Generated on first use and exported, so a process spawned later in the
    same launch reports the same id rather than opening a session of its own.
    """
    existing = os.environ.get(SESSION_ENV_VAR)
    if existing:
        return existing
    generated = uuid.uuid4().hex[:12]
    os.environ[SESSION_ENV_VAR] = generated
    return generated


def executable_path() -> str:
    """Return the real path of the running executable.

    ``sys.executable`` is what was asked for; the resolved path is what ran,
    and the two differ exactly in the cases worth logging -- a symlink into a
    bundle, or a translocated mount.
    """
    try:
        return str(Path(sys.executable).resolve())
    except OSError:
        return str(sys.executable)


def is_app_translocated(path: str | os.PathLike[str] | None = None) -> bool:
    """Whether the given executable path is running under App Translocation."""
    candidate = executable_path() if path is None else str(path)
    return APP_TRANSLOCATION_MARKER in candidate


def bundle_path(path: str | os.PathLike[str] | None = None) -> str | None:
    """Return the enclosing ``.app`` of an executable, when there is one."""
    candidate = Path(executable_path() if path is None else path)
    for parent in candidate.parents:
        if parent.suffix == ".app":
            return str(parent)
    return None


def app_version() -> str:
    """Return the application version, or ``unknown`` if it cannot be read."""
    try:
        from fpdb_3_legacy import __version__
    except Exception:  # pragma: no cover - a build without the package metadata
        return "unknown"
    return str(__version__)


def process_identity(role: str, command: list[str] | None = None) -> dict[str, Any]:
    """Collect the launch facts of this process.

    Args:
        role: ``main`` for the GUI, ``hud`` for the overlay process.
        command: the argv this process was started with, when the caller knows
            it more precisely than ``sys.argv`` does.

    Returns:
        A mapping written as-is into the banner and reusable by tests.
    """
    executable = executable_path()
    return {
        "session": session_id(),
        "role": role,
        "version": app_version(),
        "pid": os.getpid(),
        "ppid": os.getppid(),
        "executable": executable,
        "frozen": str(getattr(sys, "frozen", False)),
        "bundle": bundle_path(executable),
        "translocated": is_app_translocated(executable),
        "command": list(command) if command is not None else list(sys.argv),
    }


def format_identity(identity: dict[str, Any]) -> str:
    """Render an identity mapping as one greppable line."""
    return " ".join(f"{key}={value!r}" for key, value in identity.items())


def enable_crash_log(log_dir: str | os.PathLike[str], file_name: str) -> Path | None:
    """Keep the trace of a native crash or an uncaught exception in a file.

    A crash inside Qt raises no Python exception and bypasses ``sys.stderr``, so
    only ``faulthandler`` records it. An uncaught exception does reach
    ``sys.stderr``, but fpdb and the HUD truncate their error files on start. This
    file is appended to because the player restarts right after a problem, and
    the line written here dates the crash that may follow it.

    Args:
        log_dir: The directory of the log files.
        file_name: The file of this process in that directory.

    Returns:
        The file in use, or None if it cannot be written: the app runs without it.
    """
    path = Path(log_dir) / file_name
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        # faulthandler keeps the file open until the process ends.
        crash_log = path.open("a", encoding="utf-8")
        crash_log.write(f"--- started {datetime.now():%Y-%m-%d %H:%M:%S} pid={os.getpid()} session={session_id()}\n")
        crash_log.flush()
        faulthandler.enable(file=crash_log, all_threads=True)
    except (OSError, ValueError):
        return None
    _record_uncaught_exceptions(path)
    return path


def _record_uncaught_exceptions(path: Path) -> None:
    """Append uncaught exceptions to ``path``, then let the previous hooks run as before.

    PySide6 hands an exception raised in a slot or a virtual method to
    ``sys.excepthook``, on whichever thread raised it, and the app keeps running.
    """
    previous_hook = sys.excepthook
    previous_thread_hook = threading.excepthook

    def hook(
        exc_type: type[BaseException],
        exc_value: BaseException,
        exc_traceback: TracebackType | None,
    ) -> None:
        _append_trace(path, None, exc_type, exc_value, exc_traceback)
        # The app is already handling a failure: this must not add another one.
        with contextlib.suppress(Exception):
            previous_hook(exc_type, exc_value, exc_traceback)

    def thread_hook(args: threading.ExceptHookArgs) -> None:
        _append_trace(path, args.thread, args.exc_type, args.exc_value, args.exc_traceback)
        with contextlib.suppress(Exception):
            previous_thread_hook(args)

    sys.excepthook = hook
    threading.excepthook = thread_hook


def _append_trace(
    path: Path,
    thread: threading.Thread | None,
    exc_type: type[BaseException],
    exc_value: BaseException | None,
    exc_traceback: TracebackType | None,
) -> None:
    """Append one dated traceback. Never raises: a failure here only loses the trace."""
    with contextlib.suppress(Exception):
        # Asking to leave is not a failure. threading.excepthook receives
        # SystemExit, which its default handler ignores, and Ctrl+C is the user's.
        if issubclass(exc_type, (SystemExit, KeyboardInterrupt)):
            return
        name = (thread or threading.current_thread()).name
        header = (
            f"--- uncaught exception {datetime.now():%Y-%m-%d %H:%M:%S} "
            f"pid={os.getpid()} session={session_id()} thread={name}\n"
        )
        trace = "".join(traceback.format_exception(exc_type, exc_value, exc_traceback))
        # Opened per trace: a handle kept open would keep writing to a file the
        # user has removed since. A message can hold characters utf-8 refuses.
        with path.open("a", encoding="utf-8", errors="backslashreplace") as crash_log:
            crash_log.write(header + trace)


class _WarningLog(Protocol):
    """What the banner needs of a logger: ``logging.Logger`` and fpdb's own both qualify."""

    def warning(self, msg: object, *args: Any) -> None: ...


def log_process_identity(
    log: _WarningLog,
    role: str,
    command: list[str] | None = None,
) -> dict[str, Any]:
    """Write the launch banner and return the identity it reported.

    Keep the process banner at warning level so it survives the HUD's default
    logger threshold and is available in the persisted diagnostic log.
    """
    identity = process_identity(role, command)
    log.warning("FPDB launch identity: %s", format_identity(identity))
    if identity["translocated"]:
        log.warning(
            "This build is running under macOS App Translocation from %s. macOS gives a "
            "translocated app a throwaway identity, so Accessibility and Automation grants "
            "do not apply to it and the HUD cannot read table windows. Move %s to "
            "/Applications and launch it from there.",
            identity["executable"],
            identity["bundle"] or identity["executable"],
        )
    return identity
